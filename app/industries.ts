import { detectionCatalog, type DetectionCapability } from './surveillance-data.ts';

// Industry registry. Each industry supplies its own vocabulary, monitorable
// zones, explicitly excluded private spaces, detection capability register and
// excluded-capability list. Detection registers are industry-specific on
// purpose: a capability that is well evidenced in a warehouse aisle is not
// automatically valid in a hospital corridor.

export type IndustryId =
  | 'education'
  | 'healthcare'
  | 'aged-care'
  | 'retail'
  | 'construction'
  | 'industrial'
  | 'transport'
  | 'commercial';

export type Lexicon = {
  /** One monitored organisation, e.g. "school", "hospital", "store". */
  site: string;
  sitePlural: string;
  /** Title-case label used in headings. */
  siteTitle: string;
  /** The people the site serves and owes a duty of care to. */
  person: string;
  personPlural: string;
  /** The responding workforce. */
  staff: string;
  /** Default duty/review team named on a saved rule. */
  reviewTeam: string;
  /** Operating-hours label used by the rule scheduler. */
  hours: string;
};

export type ExcludedCapability = { name: string; why: string };

export type Industry = {
  id: IndustryId;
  name: string;
  sector: string;
  tagline: string;
  lexicon: Lexicon;
  /** Primary regulator or standard-setter for the operating context. */
  regulator: string;
  /** Areas the platform is willing to place a camera rule in. */
  zones: string[];
  /** Areas explicitly excluded from camera monitoring in this industry. */
  privateZones: string[];
  /** Incident categories used by filters, routing and analytics. */
  categories: string[];
  capabilities: DetectionCapability[];
  excluded: ExcludedCapability[];
  keyRisks: string[];
  /** Demonstration sites. */
  sites: string[];
  /** Concept workspace module ids available for this industry. */
  modules: string[];
  /** Whether the education-specific presence register applies. */
  presence: boolean;
};


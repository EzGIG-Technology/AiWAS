export const industryIds = industries.map((i) => i.id);

export function getIndustry(id: string): Industry {
  return industries.find((i) => i.id === id) ?? industries[0];
}

/** Capability register for an industry, optionally filtered by kind. */
export function industryCapabilities(id: string, kind = 'All') {
  const caps = getIndustry(id).capabilities;
  return kind === 'All' ? caps : caps.filter((c) => c.kind === kind);
}

/**
 * A saved rule must sit in a monitorable zone for the selected industry and
 * must never be placed in a zone the industry excludes.
 */
export function industryZoneError(id: string, zone: string, publicOnly: boolean) {
  const industry = getIndustry(id);
  if (industry.privateZones.includes(zone))
    return `${zone} is excluded from camera monitoring in ${industry.name.toLowerCase()}.`;
  if (!industry.zones.includes(zone) || !publicOnly)
    return 'Only approved monitored areas are available for this demonstration.';
  return '';
}

/** Counts used by the industry profile screen. */
export function capabilityMix(id: string) {
  const caps = getIndustry(id).capabilities;
  const by = (k: DetectionCapability['kind']) =>
    caps.filter((c) => c.kind === k).length;
  return {
    total: caps.length,
    video: by('Video candidate'),
    sensor: by('Sensor integration'),
    report: by('Staff report'),
    critical: caps.filter((c) => c.priority === 'Critical').length,
    excluded: getIndustry(id).excluded.length,
  };
}
